// Copies the debug APK to application/public, where the test project expects it.
// Usage: ./gradlew publishApk
tasks.register<Copy>("publishApk") {
    group = "distribution"
    description = "Builds the debug APK and copies it to application/public/food-marketplace.apk"
    dependsOn("assembleDebug")
    from(layout.buildDirectory.file("outputs/apk/debug/composeApp-debug.apk"))
    into(rootProject.layout.projectDirectory.dir("../public"))
    rename { "food-marketplace.apk" }
}
